func loadOverlay(t *testing.T, root string) Overlay {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(root, overlayRelativePath))
	if err != nil {
		t.Fatal(err)
	}
	var overlay Overlay
	if err := yaml.Unmarshal(raw, &overlay); err != nil {
		t.Fatal(err)
	}
	return overlay
}

func entityByID(overlay Overlay, id string) Entity {
	for _, ent := range overlay.Entities {
		if ent.ID == id {
			return ent
		}
	}
	return Entity{}
}

