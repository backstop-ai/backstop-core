func TestEntityRef_SchemaDerivationHelpersMatrix(t *testing.T) {
	if got := humanizePattern(`^ISSUE-[0-9]{3}(-[a-z0-9-]+)?\.issue\.md$`); !strings.Contains(got, "NNN") {
		t.Fatalf("humanizePattern issue filename = %q", got)
	}
	if got := humanizePattern(`^[0-9]{4}-[0-9]{2}-[0-9]{2}$`); got != "YYYY-MM-DD" {
		t.Fatalf("humanizePattern date = %q", got)
	}
	enumProp := map[string]any{"enum": []any{"draft", "ready"}}
	if got := fieldForm(enumProp); got != "`draft` · `ready`" {
		t.Fatalf("fieldForm enum = %q", got)
	}
	if got := fieldForm(map[string]any{"const": "issue/v1"}); got != "issue/v1" {
		t.Fatalf("fieldForm const = %q", got)
	}
	if got := fieldForm(map[string]any{"pattern": `^[a-z][a-z0-9]*(-[a-z0-9]+)*$`}); got != "slug" {
		t.Fatalf("fieldForm pattern = %q", got)
	}
	if got := fieldForm(map[string]any{"type": "integer"}); got != "integer" {
		t.Fatalf("fieldForm type = %q", got)
	}
	if got := fieldForm(nil); got != "string" {
		t.Fatalf("fieldForm nil = %q", got)
	}

	root := testRepoRoot(t)
	schema := map[string]any{
		"extends": "artifacts/base/schema.json",
		"metadata": map[string]any{
			"properties": map[string]any{
				"status": map[string]any{"type": "string"},
			},
		},
	}
	merged := mergeBase(root, schema)
	if merged == nil {
		t.Fatal("mergeBase returned nil")
	}
	if mergeBase(root, map[string]any{"extends": ""}) == nil {
		t.Fatal("mergeBase no-extends returned nil")
	}
	if mergeBase(t.TempDir(), map[string]any{"extends": "artifacts/base/schema.json"}) == nil {
		t.Fatal("mergeBase missing base file returned nil")
	}
	if mergeBase(root, map[string]any{"extends": "artifacts/base/schema.json", "metadata": "bad"}) == nil {
		t.Fatal("mergeBase bad metadata returned nil")
	}

	overlayOnly := Entity{
		ID: "pack", StatusMeanings: map[string]string{"installed": "ready", "draft": "wip"},
	}
	values := statusValues(map[string]any{}, "")
	if len(values) != 0 {
		t.Fatalf("statusValues empty path = %#v", values)
	}
	rendered, err := render(root, overlayOnly)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(rendered, "## Status") {
		t.Fatal("overlay status meanings fallback missing Status section")
	}

	noSections := sectionTable(map[string]any{})
	if noSections != "" {
		t.Fatal("sectionTable without required_sections must be empty")
	}
	withSections := sectionTable(map[string]any{
		"required_sections": []any{"Claims"},
		"optional_sections": []any{"Notes"},
	})
	if !strings.Contains(withSections, "Claims") || !strings.Contains(withSections, ">yes<") || !strings.Contains(withSections, ">no<") {
		t.Fatalf("sectionTable = %q", withSections)
	}

	illegal := illegalBlock([]string{"replaced", "obsoleted"}, Entity{ExtraIllegal: []string{"custom rule"}})
	for _, want := range []string{"replaced", "obsoleted", "custom rule"} {
		if !strings.Contains(illegal, want) {
			t.Fatalf("illegalBlock missing %q in %q", want, illegal)
		}
	}

	if got := mdCode("plain `code` tail"); got != `plain <code>code</code> tail` {
		t.Fatalf("mdCode balanced = %q", got)
	}
	if got := mdCode("unbalanced `code"); !strings.Contains(got, "unbalanced") {
		t.Fatalf("mdCode unbalanced = %q", got)
	}
	if got := escape(`<a href="x">`); got != `&lt;a href=&quot;x&quot;&gt;` {
		t.Fatalf("escape = %q", got)
	}
	if got := schemaVersion(map[string]any{
		"artifact_type": "bundle",
		"version":       "2.0",
	}, Entity{ID: "bundle"}); got != "bundle/v2" {
		t.Fatalf("schemaVersion v2 = %q", got)
	}
}

func TestEntityRef_RootResolutionAndErrorPaths(t *testing.T) {
	root := testRepoRoot(t)
	if got, err := findRepoRoot(root); err != nil || got != root {
		t.Fatalf("findRepoRoot from repo = %q, %v", got, err)
	}
	missing := filepath.Join(t.TempDir(), "nowhere")
	if _, err := findRepoRoot(missing); err == nil {
		t.Fatal("expected error when overlay missing")
	} else if !strings.Contains(err.Error(), overlayRelativePath) {
		t.Fatalf("error = %v", err)
	}
	temp := t.TempDir()
	if err := os.MkdirAll(filepath.Join(temp, "docs", "_data"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(temp, overlayRelativePath), []byte("entities: []\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := findRepoRoot(temp); err != nil {
		t.Fatalf("findRepoRoot with overlay only: %v", err)
	}
	badOverlay := filepath.Join(t.TempDir(), overlayRelativePath)
	if err := os.MkdirAll(filepath.Dir(badOverlay), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(badOverlay, []byte(":\tbad\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Run(filepath.Dir(filepath.Dir(filepath.Dir(badOverlay))), false, ioDiscard{t: t}); err == nil {
		t.Fatal("expected parse overlay error")
	}
	invalidEntity := t.TempDir()
	copyTree(t, root, invalidEntity, []string{overlayRelativePath})
	overlay := loadOverlay(t, invalidEntity)
	for i := range overlay.Entities {
		if overlay.Entities[i].ID == "issue" {
			overlay.Entities[i].Schema = "missing/schema.json"
		}
	}
	raw, _ := yaml.Marshal(overlay)
	_ = os.WriteFile(filepath.Join(invalidEntity, overlayRelativePath), raw, 0o644)
	if err := Run(invalidEntity, false, ioDiscard{t: t}); err == nil {
		t.Fatal("expected render error for missing schema")
	}
}

