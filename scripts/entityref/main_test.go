func TestEntityRef_AlsoLinksResolveToLandedRoutes(t *testing.T) {
	root := testRepoRoot(t)
	overlay := loadOverlay(t, root)
	routes := map[string]bool{}
	for _, route := range append(canonicalRoutesForTest(), extraLinkableRoutesForTest()...) {
		routes[route] = true
	}
	for _, ent := range overlay.Entities {
		for _, link := range ent.Also {
			if !strings.HasPrefix(link.Href, "/") {
				t.Fatalf("%s also-link %q is not root-relative", ent.ID, link.Href)
			}
			// Approved IA supersession: the artifact-schema-catalog target resolves on
			// origin/main, but Reference teases stay removed from entity pages.
			if strings.Contains(link.Href, "/reference/#artifact-schema-catalog") {
				t.Fatalf("%s must not link artifact schema catalog per approved IA", ent.ID)
			}
			path := link.Href
			if idx := strings.Index(path, "#"); idx >= 0 {
				path = path[:idx]
			}
			if path == "" {
				continue
			}
			if !routes[path] {
				t.Fatalf("%s also-link %q names missing route %q", ent.ID, link.Href, path)
			}
		}
	}
	pack := entityByID(overlay, "pack")
	got := map[string]bool{}
	for _, link := range pack.Also {
		got[link.Href] = true
	}
	for _, href := range []string{"/pack/examples/", "/pack/guide/"} {
		if !got[href] {
			t.Fatalf("pack also-links must include %s", href)
		}
	}
}

