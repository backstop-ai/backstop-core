func TestEntityRef_LockedLedesAndWorkPathRows(t *testing.T) {
	ledes := map[string]string{
		"plan":       "Ordered work an agent can execute. It comes from an issue or a spec.",
		"issue":      "Bounded work that does not need a bundle and spec. It becomes a plan.",
		"spec":       "Requirements and claims for a slice of feature work. It comes from a bundle. It becomes a plan.",
		"bundle":     "A larger body of work. It decomposes into specs. Each spec becomes a plan.",
		"directive":  "A backlog item. Position in BACKLOG.yml is priority. It cites the work that authorized it.",
		"adr":        "A recorded decision. It is evidence for later work. It is not a path into implementation.",
		"capability": "What a user can do, proved end to end. Specs implement the pieces. The capability verifies the journey.",
		"pack":       "A versioned set of standards, engines, and proof. Packs are not intent artifacts.",
	}
	root := testRepoRoot(t)
	overlay := loadOverlay(t, root)
	for id, lede := range ledes {
		if id == "plan" {
			planBody, err := os.ReadFile(filepath.Join(root, "docs/plan.md"))
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(planBody), lede) {
				t.Fatalf("plan page missing lede %q", lede)
			}
			continue
		}
		ent := entityByID(overlay, id)
		if ent.HeroLede != lede {
			t.Fatalf("%s overlay lede = %q, want %q", id, ent.HeroLede, lede)
		}
		path := filepath.Join(root, ent.Output)
		body, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("%s: %v", id, err)
		}
		text := string(body)
		if !strings.Contains(text, lede) {
			t.Fatalf("%s page missing lede %q", id, lede)
		}
		if strings.Contains(text, "## Sources") {
			t.Fatalf("%s page contains forbidden Sources heading", id)
		}
	}
	planBody, _ := os.ReadFile(filepath.Join(root, "docs/plan.md"))
	plan := string(planBody)
	if !strings.Contains(plan, "<th>Work</th>") || !strings.Contains(plan, "<th>Path</th>") {
		t.Fatal("plan Work path table missing Work/Path headers")
	}
	if !strings.Contains(plan, "Feature / substantial") || !strings.Contains(plan, "Small / reactive") {
		t.Fatal("plan must carry both work-path rows")
	}
	issueBody, _ := os.ReadFile(filepath.Join(root, "docs/issue.md"))
	if !strings.Contains(string(issueBody), "Small / reactive") || strings.Contains(string(issueBody), "Feature / substantial") {
		t.Fatal("issue must carry only small/reactive work-path row")
	}
	for _, id := range []string{"spec", "bundle"} {
		ent := entityByID(overlay, id)
		body, _ := os.ReadFile(filepath.Join(root, ent.Output))
		text := string(body)
		if !strings.Contains(text, "Feature / substantial") || strings.Contains(text, "Small / reactive") {
			t.Fatalf("%s must carry only feature/substantial work-path row", id)
		}
	}
	for _, id := range []string{"pack", "directive", "adr", "capability"} {
		ent := entityByID(overlay, id)
		body, _ := os.ReadFile(filepath.Join(root, ent.Output))
		if strings.Contains(string(body), "## Work path") {
			t.Fatalf("%s must not have Work path section", id)
		}
	}
}

